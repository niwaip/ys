import { afterEach, expect, test } from 'vitest';
import request from 'supertest';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../../apps/api/src/app';
let app: Awaited<ReturnType<typeof createApp>>;
let directory: string;
const auth = { Authorization: 'Bearer lifecycle-test-secret' };
afterEach(async () => { await app?.close(); if(directory) await rm(directory,{recursive:true,force:true}); });
test('immutable source batch assesses exact, weak and unmatched assets and preserves valid stage beside invalid date', async () => {
 directory=await mkdtemp(join(tmpdir(),'ys-lifecycle-'));
 app=await createApp({databaseUrl:`pglite://${directory}`,customers:[{id:'a',name:'A'},{id:'b',name:'B'}],operators:[{token:'lifecycle-test-secret',name:'Tester',customerIds:['a','b']}]});
 const http=request(app.getHttpServer());
 const ids=[];
 for(const attributes of [{product:'Widget',version:'1'},{product:'Widget'},{product:'Other',version:'1'}]) ids.push((await http.post('/api/customers/a/assets').set(auth).send({name:'host',kind:'host',attributes}).expect(201)).body.id);
 const content='source,sourceRef,product,version,eosStage,eosDate,eolStage,eolDate\nVendor bulletin,https://example.invalid/fixture,Widget,1,End of sales,2020-01-01,End of support,2026-02-30';
 const batch=(await http.post('/api/customers/a/lifecycle/batches').set(auth).send({fileName:'fixture.csv',content}).expect(201)).body;
 expect(batch.rows[0]).toMatchObject({eos:{date:'2020-01-01',dateStatus:'known'},eol:{date:null,dateStatus:'invalid'}});
 const result=(await http.post('/api/customers/a/lifecycle/assessments').set(auth).send({batchId:batch.id,assetIds:ids}).expect(201)).body;
 expect(result.items.map((x:{match:string})=>x.match)).toEqual(['exact','weak','unmatched']);
 expect(result.items[0]).toMatchObject({verification:'verified',evidence:[{eos:{status:'reached'},eol:{status:'unknown'}}]});
 expect(result.items[1].verification).toBe('needs_verification');
 expect(result.items[2].evidence).toEqual([]);
 const replay=(await http.post('/api/customers/a/lifecycle/batches').set(auth).send({fileName:'renamed.csv',content}).expect(201)).body;
 expect(replay.id).toBe(batch.id); expect(replay.replayed).toBe(true);
 await http.get(`/api/customers/b/lifecycle/batches/${batch.id}`).set(auth).expect(404);
 await http.post('/api/customers/b/lifecycle/assessments').set(auth).send({batchId:batch.id,assetIds:ids}).expect(404);
 const newer=(await http.post('/api/customers/a/lifecycle/batches').set(auth).send({fileName:'new.csv',content:content.replace('2020-01-01','2099-01-01')}).expect(201)).body;
 expect(newer.id).not.toBe(batch.id);
 const saved=(await http.get(`/api/customers/a/lifecycle/assessments/${result.id}`).set(auth).expect(200)).body;
 expect(saved).toEqual(result);
 expect((await http.get(`/api/customers/a/lifecycle/batches/${batch.id}`).set(auth)).body.content).toBe(content);
});
test('unknown dates stay unknown, version mismatch is unmatched and scopes cannot leak via object or assessment ids', async()=>{
 directory=await mkdtemp(join(tmpdir(),'ys-lifecycle-coverage-'));
 app=await createApp({databaseUrl:`pglite://${directory}`,customers:[{id:'a',name:'A'},{id:'b',name:'B'}],operators:[{token:'lifecycle-test-secret',name:'Tester',customerIds:['a','b']},{token:'limited-lifecycle-secret',name:'Limited',customerIds:['a']}]});
 const http=request(app.getHttpServer());
 const asset=(await http.post('/api/customers/a/assets').set(auth).send({name:'mismatched',kind:'host',attributes:{product:'Widget',version:'2'}})).body;
 const content='source,sourceRef,product,version,eosStage,eosDate,eolStage,eolDate\nfixture,bulletin,Widget,1,Sales,,Support,2099-12-31';
 const batch=(await http.post('/api/customers/a/lifecycle/batches').set(auth).send({fileName:'coverage.csv',content}).expect(201)).body;
 expect(batch.rows[0].eos).toMatchObject({date:null,dateStatus:'unknown'});
 const assessment=(await http.post('/api/customers/a/lifecycle/assessments').set(auth).send({batchId:batch.id,assetIds:[asset.id]}).expect(201)).body;
 expect(assessment.items[0]).toMatchObject({match:'unmatched',verification:'unknown',evidence:[]});
 await http.get(`/api/customers/b/lifecycle/assessments/${assessment.id}`).set(auth).expect(404);
 const otherBatch=(await http.post('/api/customers/b/lifecycle/batches').set(auth).send({fileName:'coverage.csv',content}).expect(201)).body;
 await http.post('/api/customers/b/lifecycle/assessments').set(auth).send({batchId:otherBatch.id,assetIds:[asset.id]}).expect(404);
 await http.get('/api/customers/b/lifecycle/batches').auth('limited-lifecycle-secret',{type:'bearer'}).expect(403);
 await http.get('/api/customers/a/lifecycle/batches').expect(401);
 await http.get('/api/customers/a/lifecycle/batches/bad').set(auth).expect(400);
 await http.post('/api/customers/a/lifecycle/batches').set(auth).send({fileName:'bad.csv',content:'product\nWidget'}).expect(400);
 expect((await http.get('/api/customers/a/imports').set(auth).expect(200)).body.items).toEqual([]);
 await app.close(); app=await createApp({databaseUrl:`pglite://${directory}`,customers:[{id:'a',name:'A'}],operators:[{token:'lifecycle-test-secret',name:'Tester',customerIds:['a']}]});
 expect((await request(app.getHttpServer()).get(`/api/customers/a/lifecycle/assessments/${assessment.id}`).set(auth).expect(200)).body).toEqual(assessment);
});
